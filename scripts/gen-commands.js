// Keeps the IPC command lists in one place.
//
// Reads the ipc handler in main.rs and rewrites the parts that must match it:
// the ACL declarations in build.rs and the app-page permissions in
// capabilities/default.json.
//
//   node scripts/gen-commands.js           rewrite both files
//   node scripts/gen-commands.js --check   exit 1 when either is out of date

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const mainPath = path.join(root, "src-tauri", "src", "main.rs");
const buildPath = path.join(root, "src-tauri", "build.rs");
const capsPath = path.join(root, "src-tauri", "capabilities", "default.json");
const permDir = path.join(root, "src-tauri", "permissions", "autogenerated");

const check = process.argv.includes("--check");

const read = (file) => fs.readFileSync(file, "utf8");
const eolOf = (text) => (text.includes("\r\n") ? "\r\n" : "\n");
const same = (a, b) => a.replace(/\r\n/g, "\n") === b.replace(/\r\n/g, "\n");

function commands() {
  const main = read(mainPath);
  const found = [...main.matchAll(/ipc::([a-z0-9_]+)\s*,/g)].map((m) => m[1]);
  if (!found.length) throw new Error("no ipc:: commands found in main.rs");
  const dupes = found.filter((name, index) => found.indexOf(name) !== index);
  if (dupes.length) throw new Error("duplicate command in main.rs: " + dupes.join(", "));
  return found;
}

const kebab = (name) => name.replace(/_/g, "-");

function buildRs(text, list) {
  const eol = eolOf(text);
  const block = [
    "    let commands: &'static [&'static str] = &[",
    "        // Generated by scripts/gen-commands.js.",
    ...list.map((name) => '        "' + name + '",'),
    "    ];",
  ].join(eol);
  const next = text.replace(
    /    let commands: &'static \[&'static str\] = &\[[\s\S]*?\n    \];/,
    () => block,
  );
  if (same(next, text)) return text;
  if (!same(next, text)) return next;
  throw new Error("build.rs: could not find the commands array to replace");
}

function capabilities(text, list) {
  const eol = eolOf(text);
  const rest = JSON.parse(text).permissions.filter((entry) => !entry.startsWith("allow-"));
  const entries = [...rest, ...list.map((name) => "allow-" + kebab(name))];
  const open = text.indexOf("[", text.indexOf('"permissions"'));
  const close = text.indexOf("]", open);
  if (open < 0 || close < 0) throw new Error("default.json: no permissions array");
  const body = entries.map((entry) => '    "' + entry + '"').join("," + eol);
  return text.slice(0, open) + "[" + eol + body + eol + "  " + text.slice(close);
}

function permissionStub(name) {
  const id = kebab(name);
  return [
    "# Automatically generated - DO NOT EDIT!",
    "",
    "[[permission]]",
    'identifier = "allow-' + id + '"',
    'description = "Enables the ' + name + ' command without any pre-configured scope."',
    'commands.allow = ["' + name + '"]',
    "",
    "[[permission]]",
    'identifier = "deny-' + id + '"',
    'description = "Denies the ' + name + ' command without any pre-configured scope."',
    'commands.deny = ["' + name + '"]',
    "",
  ].join("\n");
}

const list = commands();
const buildNext = buildRs(read(buildPath), list);
const capsNext = capabilities(read(capsPath), list);

const stale = [];
if (!same(buildNext, read(buildPath))) stale.push({ file: buildPath, next: buildNext });
if (!same(capsNext, read(capsPath))) stale.push({ file: capsPath, next: capsNext });

const missingPerms = list.filter(
  (name) => !fs.existsSync(path.join(permDir, name + ".toml")),
);

if (check) {
  if (!stale.length && !missingPerms.length) {
    console.log("ok   command lists match main.rs (" + list.length + " commands)");
    process.exit(0);
  }
  for (const entry of stale) {
    console.error("FAIL " + path.relative(root, entry.file) + " is out of date");
  }
  for (const name of missingPerms) {
    console.error("FAIL permissions/autogenerated/" + name + ".toml is missing");
  }
  console.error("run: node scripts/gen-commands.js");
  process.exit(1);
}

for (const entry of stale) {
  fs.writeFileSync(entry.file, entry.next);
  console.log("wrote " + path.relative(root, entry.file));
}
for (const name of missingPerms) {
  fs.writeFileSync(path.join(permDir, name + ".toml"), permissionStub(name));
  console.log("new   permissions/autogenerated/" + name + ".toml");
}
console.log("commands: " + list.length + (stale.length || missingPerms.length ? "" : " (already up to date)"));
